"""Writes lib/flex-metrics.json: Archivo Flex advance widths (em) at wght 800, at wdth 62 and 125, for the characters
a page title can use. Fit sizes each title in CSS from these, so the title band has its final height before the font
or any script arrives. Rerun after changing public/fonts/ArchivoFlex-Variable.woff2:  python3 scripts/flex-metrics.py"""
import json, pathlib
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

here = pathlib.Path(__file__).resolve().parent.parent
chars = [chr(c) for c in range(0x20, 0x7F) if not chr(c).islower()] + list("’–—")
out = {"note": "Generated by scripts/flex-metrics.py. Advance widths in em, uppercase, wght 800."}
for w in (62, 125):
    font = instancer.instantiateVariableFont(TTFont(here / "public/fonts/ArchivoFlex-Variable.woff2"), {"wght": 800, "wdth": w})
    cmap, hmtx, upm = font.getBestCmap(), font["hmtx"], font["head"].unitsPerEm
    out[str(w)] = {c: round(hmtx[cmap[ord(c)]][0] / upm, 4) for c in chars if ord(c) in cmap}
(here / "lib/flex-metrics.json").write_text(json.dumps(out, ensure_ascii=False, separators=(",", ":")) + "\n")
print("wrote lib/flex-metrics.json:", len(out["62"]), "characters")
