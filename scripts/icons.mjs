// Generates src/icons.generated.ts from artifact/assets/Icons/*.svg (the drawn set).
// Usage: node scripts/icons.mjs [--check]
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const dir = join(ROOT, "artifact/assets/Icons");
const icons = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = readFileSync(join(dir, f), "utf8");
  icons[f.replace(/\.svg$/, "")] = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
}
const out = `// Generated by scripts/icons.mjs from artifact/assets/Icons. Do not edit.
// 24px grid, 1.5px stroke, square caps, mitred joins: the stroke settings live on <Icon>.
export const ICONS = ${JSON.stringify(icons, null, 2)} as const;

export type IconName = keyof typeof ICONS;
`;
const target = join(ROOT, "src/icons.generated.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== out) { console.error("src/icons.generated.ts is out of date. Run: node scripts/icons.mjs"); process.exit(1); }
  console.log("icons up to date");
} else {
  writeFileSync(target, out);
  console.log(`wrote ${Object.keys(icons).length} icons`);
}
