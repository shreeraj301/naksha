// Naksha build. One source (tokens/), three outputs:
//   dist/css       naksha.css (variables, themes, fonts, type classes), custom-media.css, components.css
//   dist/js        tokens.js + tokens.d.ts
//   dist/artifact  the full Claude Design System artifact: artifact/ plus generated tokens, bundle.css, fonts
// Usage: node scripts/build.mjs [--src tokens] [--out dist]
import { mkdirSync, writeFileSync, copyFileSync, cpSync, readdirSync, existsSync, rmSync } from "node:fs";
import { join, resolve, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { loadSource, tokensFor, resolveToken, cssDecl, cssValue, fontStack, isAlias, aliasPath, here } from "./tokens.mjs";

const ROOT = resolve(here(import.meta.url), "..");
const arg = (k, d) => {
  const i = process.argv.indexOf(k);
  return i > -1 ? resolve(process.argv[i + 1]) : d;
};
const SRC = arg("--src", join(ROOT, "tokens"));
const OUT = arg("--out", join(ROOT, "dist"));
const NAME = "Naksha";
const HEADER = `/* ${NAME} · generated by scripts/build.mjs from tokens/. Do not edit. */`;

export function build(src = SRC, out = OUT) {
  const source = loadSource(src);
  const themes = Object.keys(source.themes);
  const maps = Object.fromEntries(themes.map((t) => [t, tokensFor(source, t)]));
  const light = maps[source.defaultTheme];

  // Which tokens come from a theme file (they change per theme)
  const themed = new Set();
  for (const t of themes) for (const f of source.themes[t]) for (const [k, v] of maps[t]) if (v.file === f.file) themed.add(k);

  // Validate: every token resolves in every theme
  for (const t of themes) for (const tok of maps[t].values()) resolveToken(maps[t], tok);

  const all = [...light.values()];
  const shared = all.filter((t) => !themed.has(t.path.join(".")));
  const byTop = (top) => shared.filter((t) => t.path[0] === top);
  const isPrimColor = (t) => t.type === "color";
  const typeStyles = shared.filter((t) => t.type === "typography");
  const fonts = source.base.find((f) => f.tree.$extensions?.["dev.naksha"]?.fontFiles)?.tree.$extensions["dev.naksha"].fontFiles ?? [];

  if (existsSync(out)) rmSync(out, { recursive: true });
  for (const d of ["css", "js", "artifact", "fonts"]) mkdirSync(join(out, d), { recursive: true });

  // ---------- CSS ----------
  // Products get rem (grows with the reader's browser font size, ADR 0010); the artifact keeps px.
  const KEEP_PX = (t) => t.path[0] === "border" || t.path[0] === "bp" || t.name === "radius-round";
  const toRem = (css) => css.replace(/(-?\d*\.?\d+)px\b/g, (m, n) => (Number(n) === 0 ? "0" : `${Number((Number(n) / 16).toFixed(4))}rem`));
  const remOf = (t, css, rem) => (rem && t.type === "dimension" && !KEEP_PX(t) ? toRem(css) : css);
  const decl = (map, t, { fluid = false, rem = false } = {}) => `  --${t.name}: ${fluid && t.ext.fluid ? t.ext.fluid : remOf(t, cssDecl(map, t), rem)};`;
  const themedFor = (theme) => [...maps[theme].values()].filter((t) => themed.has(t.path.join(".")));
  const order = ["space", "radius", "size", "layout", "bp", "border", "dur", "ease", "z"];
  const sharedVars = order.flatMap(byTop).filter((t) => t.type !== "color");
  const typeClass = (t, { fluid = false, rem = false } = {}) => {
    const v = resolveToken(light, t);
    const fam = aliasPath(t.value.fontFamily).replace("font.", "");
    let size = cssValue("dimension", v.fontSize);
    if (rem) size = toRem(size);
    if (fluid && t.ext.fluid) size = t.ext.fluid;
    return `.${t.path.at(-1)} { font-family: var(--font-${fam}); font-size: ${size}; line-height: ${v.lineHeight}; font-weight: ${v.fontWeight}; letter-spacing: ${t.ext.letterSpacingEm}em; }`;
  };
  const fontFace = (f, prefix) =>
    `@font-face { font-family: "${f.family}"; src: url("${prefix}${basename(f.file)}") format("woff2"); font-weight: ${f.weight}; font-style: ${f.style ?? "normal"}; font-display: swap; }`;
  const LAYERS = "@layer naksha.tokens, naksha.base, naksha.components;";
  const wrap = (layer, body, on) => (on ? `@layer ${layer} {\n${body}\n}` : body);

  // naksha.css (products): layered, rem, fluid, dark follows the OS when no data-theme is set.
  // artifact tokens.css: the artifact's own format, unlayered, px, fixed sizes.
  const cssBody = (fontPrefix, { product }) => {
    const L = [HEADER];
    if (product) L.push(LAYERS);
    for (const f of fonts) L.push(fontFace(f, fontPrefix));
    const T = [];
    const lightVars = [...shared.filter(isPrimColor), ...themedFor(source.defaultTheme)].map((t) => decl(light, t));
    T.push(`:root, [data-theme="${source.defaultTheme}"] {\n${lightVars.join("\n")}\n}`);
    for (const th of themes.filter((x) => x !== source.defaultTheme)) {
      const vars = themedFor(th).map((t) => decl(maps[th], t)).join("\n");
      T.push(`[data-theme="${th}"] {\n${vars}\n}`);
      if (product && th === "dark") T.push(`@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n${vars.replaceAll("\n", "\n  ").replace(/^/, "  ")}\n  }\n}`);
    }
    const opt = { fluid: product, rem: product };
    const rest = [...sharedVars.map((t) => decl(light, t, opt)), ...byTop("font").map((t) => decl(light, t)), ...byTop("weight").map((t) => decl(light, t))];
    T.push(`:root {\n${rest.join("\n")}\n}`);
    if (product) T.push(`@media (prefers-reduced-motion: reduce) {\n  :root {\n    --dur-press: 0ms;\n    --dur-overlay: 150ms;\n    --dur-page: 150ms;\n    --dur-hero: 150ms;\n  }\n}`);
    L.push(wrap("naksha.tokens", T.join("\n"), product));
    const B = typeStyles.map((t) => typeClass(t, opt));
    if (product) {
      const bp = resolveToken(light, light.get("bp.medium"));
      const steps = typeStyles.filter((t) => t.ext.mobile).map((t) => `  .${t.path.at(-1)} { font-size: ${toRem(cssValue("dimension", t.ext.mobile))}; }`);
      if (steps.length) B.push(`@media (max-width: ${bp.value - 0.02}px) {\n${steps.join("\n")}\n}`);
    }
    L.push(wrap("naksha.base", B.join("\n"), product));
    return L.join("\n") + "\n";
  };

  writeFileSync(join(out, "css/naksha.css"), cssBody("../fonts/", { product: true }));
  const cm = byTop("bp").map((t) => {
    const v = resolveToken(light, t);
    return `@custom-media --bp-${t.path[1]} (min-width: ${v.value}${v.unit});`;
  });
  writeFileSync(join(out, "css/custom-media.css"), [HEADER, "/* Needs postcss-custom-media, or copy the queries. */", ...cm].join("\n") + "\n");
  copyFileSync(join(ROOT, "css/components.css"), join(out, "css/components.css"));
  for (const f of readdirSync(join(ROOT, "fonts")).filter((f) => f.endsWith(".woff2"))) copyFileSync(join(ROOT, "fonts", f), join(out, "fonts", f));

  // ---------- JS ----------
  const resolvedCSS = (map, list) => Object.fromEntries(list.map((t) => [t.name, cssValue(t.type, resolveToken(map, t), t.ext)]));
  const colorNames = [...shared.filter(isPrimColor), ...themedFor(source.defaultTheme).filter(isPrimColor)];
  const color = Object.fromEntries(themes.map((th) => [th, resolvedCSS(maps[th], colorNames.map((t) => maps[th].get(t.path.join("."))))]));
  const num = (top) => Object.fromEntries(byTop(top).map((t) => {
    const v = resolveToken(light, t);
    return [t.path.slice(1).join("-"), typeof v === "object" && "value" in v ? v.value : v];
  }));
  const js = {
    color,
    shadow: Object.fromEntries(themes.map((th) => [th, resolvedCSS(maps[th], themedFor(th).filter((t) => t.type === "shadow"))])),
    space: num("space"), radius: num("radius"), size: num("size"), border: num("border"),
    layout: num("layout"), bp: num("bp"), z: num("z"),
    dur: num("dur"), ease: num("ease"),
    font: Object.fromEntries(byTop("font").map((t) => [t.path[1], cssValue("fontFamily", resolveToken(light, t))])),
    weight: num("weight"),
    text: Object.fromEntries(typeStyles.map((t) => {
      const v = resolveToken(light, t);
      return [t.path.at(-1), { fontFamily: fontStack(v.fontFamily), fontSize: v.fontSize.value, lineHeight: v.lineHeight, fontWeight: v.fontWeight, letterSpacing: `${t.ext.letterSpacingEm}em` }];
    })),
  };
  const varNames = [...new Set([...light.values()].filter((t) => t.type !== "typography").map((t) => t.name))];
  const jsOut = [
    `// ${NAME} · generated by scripts/build.mjs from tokens/. Do not edit.`,
    `// Numbers are px (space, radius, size, border, layout, bp) or ms (dur).`,
    ...Object.entries(js).map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 2)};`),
    `/** CSS variable reference for a token name, e.g. cssVar("bg-canvas") -> "var(--bg-canvas)". */`,
    `export const cssVar = (name) => \`var(--\${name})\`;`,
    `export const names = ${JSON.stringify(varNames)};`,
  ].join("\n\n");
  writeFileSync(join(out, "js/tokens.js"), jsOut + "\n");
  const keys = (o) => Object.keys(o).map((k) => JSON.stringify(k)).join(" | ") || "never";
  const rec = (o, v) => `Readonly<Record<${keys(o)}, ${v}>>`;
  const dts = [
    `// ${NAME} · generated. Do not edit.`,
    `export type Theme = ${keys(color)};`,
    `export type ColorName = ${keys(color[source.defaultTheme])};`,
    `export type TokenName = ${varNames.map((n) => JSON.stringify(n)).join(" | ")};`,
    `export declare const color: Readonly<Record<Theme, Readonly<Record<ColorName, string>>>>;`,
    `export declare const shadow: Readonly<Record<Theme, ${rec(js.shadow[source.defaultTheme], "string")}>>;`,
    ...["space", "radius", "size", "border", "layout", "bp", "z", "dur", "weight"].map((k) => `export declare const ${k}: ${rec(js[k], "number")};`),
    `export declare const ease: ${rec(js.ease, "readonly [number, number, number, number]")};`,
    `export declare const font: ${rec(js.font, "string")};`,
    `export interface TextStyle { fontFamily: string; fontSize: number; lineHeight: number; fontWeight: number; letterSpacing: string }`,
    `export declare const text: ${rec(js.text, "TextStyle")};`,
    `export declare function cssVar(name: TokenName): string;`,
    `export declare const names: readonly TokenName[];`,
  ].join("\n");
  writeFileSync(join(out, "js/tokens.d.ts"), dts + "\n");

  // ---------- Claude artifact ----------
  // The artifact type requires this exact first line, dash included.
  writeFileSync(join(out, "artifact/tokens.css"), cssBody("fonts/", { product: false }).replace(HEADER, `/* ${NAME} — generated from tokens.json */`));
  const desc = (top) => source.base.map((f) => f.tree[top]?.$description).find(Boolean);
  const aval = (map, t) => (isAlias(t.value) ? `{${aliasPath(t.value).replaceAll(".", "-")}}` : cssValue(t.type, resolveToken(map, t), t.ext));
  const list = (top) => byTop(top).filter((t) => t.type !== "color").map((t) => ({ name: t.name, value: aval(light, t), usage: t.description }));
  const groups = [];
  for (const t of typeStyles) {
    const g = t.ext.group;
    let grp = groups.find((x) => x.name === g);
    if (!grp) groups.push((grp = { name: g, family: aliasPath(t.value.fontFamily).replace("font.", ""), styles: [] }));
    const v = resolveToken(light, t);
    grp.styles.push({ name: t.path.at(-1), fontSize: cssValue("dimension", v.fontSize), lineHeight: v.lineHeight, fontWeight: v.fontWeight, letterSpacing: `${t.ext.letterSpacingEm}em`, sample: t.ext.sample, usage: t.description });
  }
  const artifact = {
    name: NAME,
    version: 3,
    color: {
      themes: themes.map((id) => ({ id, name: id[0].toUpperCase() + id.slice(1) })),
      note: "Two tiers. Primitives (stone, hues, alpha) hold raw values pinned to the portfolio CSS; design with the semantic tokens that alias them.",
      tokens: [
        ...shared.filter(isPrimColor).map((t) => ({ name: t.name, value: cssValue("color", t.value), usage: t.description || "Primitive. Use a semantic token instead." })),
        ...themedFor(source.defaultTheme).filter(isPrimColor).map((t) => ({
          name: t.name,
          value: Object.fromEntries(themes.map((th) => [th, aval(maps[th], maps[th].get(t.path.join(".")))])),
          usage: t.description,
        })),
      ],
    },
    type: {
      fonts: fonts.map((f) => ({ ...f, file: `fonts/${basename(f.file)}` })),
      families: Object.fromEntries(byTop("font").filter((t) => t.path[1] !== "devanagari").map((t) => [t.path[1], cssValue("fontFamily", t.value)])),
      groups,
    },
    spacing: { note: desc("space") ?? "", tokens: list("space") },
    radius: { note: light.get("radius.control") && source.base.map((f) => f.tree.radius?.$description).find(Boolean), tokens: list("radius") },
    shadow: {
      note: "The page is flat. One shadow, only for things that float, and they keep their hairline.",
      tokens: themedFor(source.defaultTheme).filter((t) => t.type === "shadow").map((t) => ({
        name: t.name, value: Object.fromEntries(themes.map((th) => [th, cssValue("shadow", resolveToken(maps[th], maps[th].get(t.path.join("."))))])), usage: t.description,
      })),
    },
    size: { tokens: list("size") },
    layout: { tokens: [...list("layout"), ...list("bp")] },
    border: { tokens: byTop("border").filter((t) => t.type === "dimension").map((t) => ({ name: t.name, value: aval(light, t), usage: t.description })) },
    duration: { note: desc("dur") ?? "", tokens: list("dur") },
    easing: { tokens: list("ease") },
    zIndex: { tokens: list("z") },
  };
  writeFileSync(join(out, "artifact/tokens.json"), JSON.stringify(artifact, null, 1) + "\n");
  // Hand-made artifact files (previews, READMEs, icons, index), then the generated ones on top.
  cpSync(join(ROOT, "artifact"), join(out, "artifact"), { recursive: true, force: false, errorOnExist: false });
  mkdirSync(join(out, "artifact/components"), { recursive: true });
  copyFileSync(join(ROOT, "css/components.css"), join(out, "artifact/components/bundle.css"));
  copyFileSync(join(ROOT, "CHANGELOG.md"), join(out, "artifact/CHANGELOG.md"));
  mkdirSync(join(out, "artifact/fonts"), { recursive: true });
  for (const f of readdirSync(join(ROOT, "fonts")).filter((f) => f.endsWith(".woff2"))) copyFileSync(join(ROOT, "fonts", f), join(out, "artifact/fonts", f));

  return { out, counts: { tokens: light.size, themed: themed.size, themes: themes.length, typeStyles: typeStyles.length } };
}


if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = build();
  console.log(`built ${r.counts.tokens} tokens (${r.counts.themed} themed × ${r.counts.themes} themes, ${r.counts.typeStyles} type styles) -> ${r.out}`);
}
