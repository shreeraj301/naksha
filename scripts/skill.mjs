// Generates the Naksha agent docs from the same sources as everything else:
//   skills/naksha/SKILL.md                      Agent Skill (agentskills.io layout), committed so `npx skills add` can install it
//   skills/naksha/references/tokens.md          every token, both themes
//   skills/naksha/references/brand-book.md      the brand book
//   skills/naksha/references/components/*.md    one page per component
//   dist/agents/block.md                        the marked block `naksha init-agents` writes into a product's AGENTS.md / CLAUDE.md
// Usage: node scripts/skill.mjs [--check]   (--check fails if the committed skill is out of date)
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, rmSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadSource, tokensFor, resolveToken, cssValue, isAlias, aliasPath } from "./tokens.mjs";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
const SKILL = join(ROOT, "skills/naksha");
const NOTE = "<!-- Generated by scripts/skill.mjs from tokens/, artifact/README.md and artifact/components/*/README.md. Do not edit. -->";
const REPO = "https://github.com/shreeraj301/naksha";

export function generate() {
  const src = loadSource(join(ROOT, "tokens"));
  const light = tokensFor(src, "light");
  const dark = tokensFor(src, "dark");
  const themedFiles = new Set(Object.values(src.themes).flat().map((f) => f.file));
  const val = (map, t) => cssValue(t.type, resolveToken(map, t), t.ext);
  const ref = (t) => (isAlias(t.value) ? aliasPath(t.value).replace(".", "-") : "");
  const all = [...light.values()];
  const semantic = all.filter((t) => t.type === "color" && themedFiles.has(t.file));
  const typeStyles = all.filter((t) => t.type === "typography");
  const group = (top) => all.filter((t) => t.path[0] === top && t.type !== "color" && t.type !== "typography");
  const esc = (s) => String(s).replaceAll("|", "\\|").replace(/\s+/g, " ").trim();

  const comps = readdirSync(join(ROOT, "artifact/components"))
    .filter((d) => d !== "Cover" && existsSync(join(ROOT, "artifact/components", d, "README.md")))
    .map((name) => {
      const md = readFileSync(join(ROOT, "artifact/components", name, "README.md"), "utf8");
      const first = md.replace(/^# .*\n+/, "").split(/\n\n/)[0].replace(/\s+/g, " ").trim();
      return { name, md, first };
    });
  const brand = readFileSync(join(ROOT, "artifact/README.md"), "utf8");
  const intro = brand.split(/\n\n/)[0].trim();

  const semanticRows = semantic.map((t) => `| \`${t.name}\` | ${val(light, t)} (${ref(t)}) | ${val(dark, dark.get(t.path.join(".")))} (${ref(dark.get(t.path.join(".")))}) | ${esc(t.description)} |`);
  const typeRows = typeStyles.map((t) => {
    const v = resolveToken(light, t);
    const fluid = t.ext.fluid ? ` (fluid from ${t.ext.min.value}px)` : t.ext.mobile ? ` (${t.ext.mobile.value}px below 600px)` : "";
    return `| \`.${t.path.at(-1)}\` | ${aliasPath(t.value.fontFamily).replace("font.", "")} | ${v.fontSize.value}px${fluid} / ${v.lineHeight} / ${v.fontWeight} | ${esc(t.description)} |`;
  });
  const listOf = (top) => group(top).map((t) => `\`${t.name}\` ${val(light, t)}`).join(", ");

  const rules = `1. **Use a Naksha component for anything it covers.** Classes start with \`nk-\`; in React, import from \`naksha\`. The list is under Components in the Naksha skill and in the repo. Do not rebuild one from divs.
2. **Values come from tokens only.** Colours, space, sizes, type, motion: \`var(--token-name)\`. No hex, rgb() or named colours, and no px above 2 (Naksha's own lint rejects them; hold product code to the same rule). Pick a token by what it means, never because the colour happens to match.
3. **Overrides are layout only.** React components take \`styles\` for margin, width, flex or grid placement, position and z-index. Never colour, type, border or inner padding. If a look is missing, it needs a Naksha variant (ADR 0009).
4. **Paper and ink.** Square edges (\`radius-control\` and \`radius-surface\` are 0); hairlines (\`border-default\`), not shadows; only floating things get \`shadow-overlay\`. One \`primary\` button per region.
5. **Text contrast.** Body text is \`fg-default\`, secondary \`fg-muted\`. \`fg-subtle\` is for \`bg-canvas\` and \`bg-raised\` only, never \`bg-subtle\` (4.07:1). Status always pairs colour with an icon and words.
6. **Themes.** \`data-theme="light"\` or \`"dark"\` on \`<html>\`; with neither, \`naksha.css\` follows the OS. Never write theme-specific values in a product.
7. **India first.** Money and numbers with \`Intl\` and \`en-IN\` (₹1,25,000). Dates as 18 Dec 2026, caps in mono (18 DEC 2026), month cut to three letters ("Sept" becomes "Sep").
8. **AI surfaces.** People are round, agents are square and named. Facts carry numbered sources. While a reply streams, Send becomes Stop. Enter never sends while an input method is composing.
9. **Accessibility is the floor, not a feature.** WCAG 2.2 AA; visible focus on every stop; real buttons, links and labels; works in forced colours and with reduced motion.`;

  const setup = `\`\`\`html
<html data-theme="light">
  <link rel="stylesheet" href="/node_modules/naksha/dist/css/naksha.css">       <!-- or import "naksha/css" -->
  <link rel="stylesheet" href="/node_modules/naksha/dist/css/components.css">   <!-- or import "naksha/css/components" -->
\`\`\`

\`\`\`js
import { color, space, cssVar } from "naksha/tokens";   // values for JS (px numbers)
import { layoutStyle } from "naksha";                     // React helpers and, from Phase 1, components
\`\`\`

Naksha's CSS sits in cascade layers (\`naksha.tokens\`, \`naksha.base\`, \`naksha.components\`), so a product's own CSS outside a layer wins without \`!important\`.`;

  const review = `Every finding cites evidence: a file and line, a rendered state (theme, width, forced colours, reduced motion), or a source. Mark each area **good**, **needs work** or **not inspected**. Missing evidence is "not inspected", never a pass.

Check, in this order: the right component is used; tokens only (no raw values); layout-only overrides; both themes; keyboard path and visible focus; forced colours; reduced motion; empty, loading, error and long-content states; narrow and wide widths; Indian formats.`;

  const skill = `---
name: naksha
description: Build or review UI with Naksha, Shreeraj Narwade's design system (tokens, CSS components, React on React Aria). Use when a project links naksha.css, imports from "naksha", or asks for Naksha.
---

${NOTE}

# Naksha

Version ${pkg.version}.

${intro}

Source of truth: ${REPO}. Visual reference: the Naksha design system artifact on claude.ai.

## Rules

${rules}

## Setup

${setup}

## Colour (semantic tokens)

Light and dark value, with the primitive each aliases. Primitives (\`stone-*\`, hues, alpha) are never used directly.

| Token | Light | Dark | Use |
| --- | --- | --- | --- |
${semanticRows.join("\n")}

## Type

| Class | Family | Size / line height / weight | Use |
| --- | --- | --- | --- |
${typeRows.join("\n")}

## Space, size, motion

- Space: ${listOf("space")}
- Size: ${listOf("size")}
- Radius: ${listOf("radius")}
- Layout: ${listOf("layout")}
- Breakpoints (min-width): ${listOf("bp")}
- Duration: ${listOf("dur")}
- Easing: ${listOf("ease")}

Every token, both themes: [references/tokens.md](references/tokens.md).

## Components

| Component | What it is for |
| --- | --- |
${comps.map((c) => `| [${c.name}](references/components/${c.name}.md) | ${esc(c.first)} |`).join("\n")}

The brand book (voice, colour, type, layout, motion, iconography, AI patterns, accessibility): [references/brand-book.md](references/brand-book.md).

## Reviewing UI built with Naksha

${review}
`;

  const tokensMd = `${NOTE}

# Naksha tokens

| Token | Type | Light | Dark | Use |
| --- | --- | --- | --- | --- |
${all.filter((t) => t.type !== "typography").map((t) => {
    const d = dark.get(t.path.join("."));
    const lv = val(light, t), dv = val(dark, d);
    return `| \`${t.name}\` | ${t.type} | ${esc(lv)} | ${dv === lv ? "same" : esc(dv)} | ${esc(t.description)} |`;
  }).join("\n")}
`;

  const block = `<!-- NAKSHA:START (managed by \`naksha init-agents\`; do not edit between the markers) -->
## Naksha

This project's UI uses Naksha (${pkg.version}), Shreeraj Narwade's design system. Source: ${REPO}. If the \`naksha\` Agent Skill is installed, read it before writing UI.

${rules}

When reviewing UI: every finding cites a file and line, a rendered state or a source; mark areas good, needs work or not inspected; missing evidence is never a pass.
<!-- NAKSHA:END -->
`;

  return {
    files: {
      "SKILL.md": skill,
      "references/tokens.md": tokensMd,
      "references/brand-book.md": `${NOTE}\n\n# Naksha brand book\n\n${brand}`,
      ...Object.fromEntries(comps.map((c) => [`references/components/${c.name}.md`, `${NOTE}\n\n${c.md}`])),
    },
    block,
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { files, block } = generate();
  if (process.argv.includes("--check")) {
    const stale = Object.entries(files).filter(([p, c]) => !existsSync(join(SKILL, p)) || readFileSync(join(SKILL, p), "utf8") !== c).map(([p]) => p);
    if (stale.length) {
      console.error(`skills/naksha is out of date (${stale.length} files, e.g. ${stale[0]}). Run: node scripts/skill.mjs`);
      process.exit(1);
    }
    console.log("skills/naksha is up to date");
  } else {
    if (existsSync(SKILL)) rmSync(SKILL, { recursive: true });
    for (const [p, c] of Object.entries(files)) {
      mkdirSync(join(SKILL, p, ".."), { recursive: true });
      writeFileSync(join(SKILL, p), c);
    }
    mkdirSync(join(ROOT, "dist/agents"), { recursive: true });
    writeFileSync(join(ROOT, "dist/agents/block.md"), block);
    console.log(`wrote skills/naksha (${Object.keys(files).length} files) and dist/agents/block.md`);
  }
}
